import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'

const rootDir = process.cwd()
const skillsRoot = path.join(rootDir, 'electron', 'runtime', 'agent', 'skills', 'library')
const packageJsonPath = path.join(rootDir, 'package.json')
const outputPath = path.join(rootDir, 'src', 'shared', 'skill-pack-metadata.ts')

function listFiles(root) {
  const queue = [root]
  const files = []
  while (queue.length > 0) {
    const current = queue.pop()
    if (!current || !fs.existsSync(current)) continue
    const entries = fs.readdirSync(current, { withFileTypes: true })
    for (const entry of entries) {
      if (entry.name.startsWith('.')) continue
      const fullPath = path.join(current, entry.name)
      if (entry.isDirectory()) {
        queue.push(fullPath)
        continue
      }
      files.push(fullPath)
    }
  }
  return files.sort((a, b) => a.localeCompare(b))
}

function calculateChecksum(root) {
  const hash = crypto.createHash('sha256')
  const files = listFiles(root)
  for (const file of files) {
    const relativePath = path.relative(rootDir, file).replace(/\\/g, '/')
    hash.update(relativePath)
    hash.update('\0')
    hash.update(fs.readFileSync(file))
    hash.update('\0')
  }
  return hash.digest('hex')
}

function readPackageVersion() {
  const payload = JSON.parse(fs.readFileSync(packageJsonPath, 'utf-8'))
  if (typeof payload.version === 'string' && payload.version.trim().length > 0) {
    return payload.version.trim()
  }
  return '0.0.0'
}

function toTsContent(version, checksum, builtAt) {
  return `import type { SkillPackMetadata } from './backend-api'

// This file is generated by scripts/generate-skill-pack-metadata.mjs.
export const SKILL_PACK_METADATA: SkillPackMetadata = {
  skill_pack_version: '${version}',
  skill_pack_checksum: '${checksum}',
  built_at: '${builtAt}',
}
`
}

function parseExisting(content) {
  if (!content) return null
  const versionMatch = content.match(/skill_pack_version:\s*'([^']+)'/)
  const checksumMatch = content.match(/skill_pack_checksum:\s*'([^']+)'/)
  const builtAtMatch = content.match(/built_at:\s*'([^']+)'/)
  if (!versionMatch || !checksumMatch || !builtAtMatch) {
    return null
  }
  return {
    skill_pack_version: versionMatch[1],
    skill_pack_checksum: checksumMatch[1],
    built_at: builtAtMatch[1],
  }
}

const version = process.env.SKILL_PACK_VERSION?.trim() || readPackageVersion()
const checksum = calculateChecksum(skillsRoot)
const prevContent = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf-8') : null
const previousMetadata = parseExisting(prevContent)
const builtAt = (
  previousMetadata
  && previousMetadata.skill_pack_version === version
  && previousMetadata.skill_pack_checksum === checksum
)
  ? previousMetadata.built_at
  : new Date().toISOString()

const nextContent = toTsContent(version, checksum, builtAt)

if (prevContent !== nextContent) {
  fs.writeFileSync(outputPath, nextContent, 'utf-8')
  console.log(`[skill-pack-meta] updated ${path.relative(rootDir, outputPath)}`)
} else {
  console.log('[skill-pack-meta] unchanged')
}
